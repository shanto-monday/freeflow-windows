# Builds FreeFlow.exe with the C# compiler that ships with Windows. No installs needed.
#   FreeFlow.exe              = your copy (Groq key from secret.key built in). Never share or upload it.
#   dist\FreeFlow.exe         = public copy (no key). GitHub Releases + auto update use this one.
#   dist\FreeFlow-Windows.zip = public exe + HOW-TO-USE.txt
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$version = (Get-Content "$here\VERSION" -Raw).Trim()
$repo = (Get-Content "$here\repo.txt" -Raw).Trim()

Add-Type -AssemblyName System.Drawing
# icon: 256px PNG wrapped in an .ico
$src = [System.Drawing.Image]::FromFile("$here\src\icon-source.png")
$bmp = New-Object System.Drawing.Bitmap 256,256
$g = [System.Drawing.Graphics]::FromImage($bmp); $g.InterpolationMode = 'HighQualityBicubic'; $g.DrawImage($src,0,0,256,256); $g.Dispose(); $src.Dispose()
$ms = New-Object System.IO.MemoryStream; $bmp.Save($ms,[System.Drawing.Imaging.ImageFormat]::Png); $png = $ms.ToArray()
$ico = New-Object System.IO.MemoryStream; $w = New-Object System.IO.BinaryWriter $ico
$w.Write([uint16]0); $w.Write([uint16]1); $w.Write([uint16]1)
$w.Write([byte]0); $w.Write([byte]0); $w.Write([byte]0); $w.Write([byte]0); $w.Write([uint16]1); $w.Write([uint16]32); $w.Write([uint32]$png.Length); $w.Write([uint32]22)
$w.Write($png); $w.Flush(); [IO.File]::WriteAllBytes("$here\src\app.ico",$ico.ToArray())

$fw = "$env:WINDIR\Microsoft.NET\Framework64\v4.0.30319"
$gen = "$here\src\BuildInfo.g.cs"
function Build($out, $key) {
  $k = $key -replace '[^A-Za-z0-9_\-]', ''
  $p = ($version + '.0.0.0').Split('.')
  $asm = "$($p[0]).$($p[1]).$($p[2]).0"
  $code = @"
// generated by build.ps1, do not edit, not in git
[assembly: System.Reflection.AssemblyVersion("$asm")]
[assembly: System.Reflection.AssemblyFileVersion("$asm")]
[assembly: System.Reflection.AssemblyProduct("FreeFlow for Windows")]
[assembly: System.Reflection.AssemblyTitle("FreeFlow")]
namespace FreeFlowWin { static class BuildInfo {
  public const string Version = "$version";
  public const string Repo = "$repo";
  public const string BuiltInKey = "$k";
} }
"@
  [IO.File]::WriteAllText($gen, $code)
  & "$fw\csc.exe" /nologo /target:winexe /platform:x64 /optimize+ /out:"$out" /win32icon:"$here\src\app.ico" `
    "/resource:$here\prompt.txt,prompt.txt" `
    /r:System.dll /r:System.Drawing.dll /r:System.Windows.Forms.dll /r:System.Net.Http.dll /r:System.Security.dll /r:System.Web.Extensions.dll `
    /r:System.Core.dll /r:System.IO.Compression.dll /r:System.IO.Compression.FileSystem.dll `
    "$here\src\FreeFlow.cs" "$here\src\Ui.cs" "$here\src\Engine.cs" "$here\src\Update.cs" $gen
  $rc = $LASTEXITCODE
  Remove-Item $gen -ErrorAction SilentlyContinue   # never leave the key on disk in src
  if ($rc -ne 0) { throw "build failed" }
  Write-Host "Built $out ($version)"
}

$secret = ""
if (Test-Path "$here\secret.key") { $secret = (Get-Content "$here\secret.key" -Raw).Trim() }
Build "$here\FreeFlow.exe" $secret
New-Item -ItemType Directory -Force "$here\dist" | Out-Null
Build "$here\dist\FreeFlow.exe" ""
Copy-Item "$here\HOW-TO-USE.txt" "$here\dist\HOW-TO-USE.txt" -Force
Compress-Archive -Force -Path "$here\dist\FreeFlow.exe","$here\dist\HOW-TO-USE.txt" -DestinationPath "$here\dist\FreeFlow-Windows.zip"
Write-Host "Public build: $here\dist"
